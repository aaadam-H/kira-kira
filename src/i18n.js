const PRAISE = {
  ms: ['Betul!', 'Pandai!', 'Syabas!', 'Tepat sekali!'],
  en: ['Correct!', 'Well done!', 'Great!', 'Spot on!'],
};

export function t(lang, key, params = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.ms[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
}

export function praise(lang) {
  const list = PRAISE[lang] || PRAISE.ms;
  return list[Math.floor(Math.random() * list.length)];
}
